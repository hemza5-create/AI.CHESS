import { Chess } from 'chess.js';
import type { SupportedLanguage } from '../i18n/translations.ts';

export type OpeningCategory = 'open' | 'semiOpen' | 'closed' | 'indian' | 'flank';

export interface OpeningLocalizedContent {
  name: string;
  summary: string;
  whitePlan: string;
  blackPlan: string;
  moveNotes: string[];
}

export interface ChessOpeningDefinition {
  id: string;
  eco: string;
  category: OpeningCategory;
  preferredSide: 'w' | 'b';
  moves: string[];
  localized: Record<SupportedLanguage, OpeningLocalizedContent>;
}

export interface OpeningTimelineStep {
  ply: number; // 0 = initial board, 1..N = after move N
  fen: string;
  san: string | null;
  from: string | null;
  to: string | null;
  turnAfter: 'w' | 'b';
  nextExpected: {
    san: string;
    from: string;
    to: string;
  } | null;
}

export function buildOpeningTimeline(moves: string[]): OpeningTimelineStep[] {
  const chess = new Chess();
  const parsedMoves: Array<{
    san: string;
    from: string;
    to: string;
    fenAfter: string;
    turnAfter: 'w' | 'b';
  }> = [];

  for (const san of moves) {
    const result = chess.move(san);
    if (!result) {
      throw new Error(`Invalid opening move "${san}" in sequence: ${moves.join(' ')}`);
    }
    parsedMoves.push({
      san: result.san,
      from: result.from,
      to: result.to,
      fenAfter: chess.fen(),
      turnAfter: chess.turn(),
    });
  }

  const startChess = new Chess();
  const timeline: OpeningTimelineStep[] = [
    {
      ply: 0,
      fen: startChess.fen(),
      san: null,
      from: null,
      to: null,
      turnAfter: 'w',
      nextExpected:
        parsedMoves.length > 0
          ? { san: parsedMoves[0].san, from: parsedMoves[0].from, to: parsedMoves[0].to }
          : null,
    },
  ];

  for (let i = 0; i < parsedMoves.length; i++) {
    const curr = parsedMoves[i];
    const next = i + 1 < parsedMoves.length ? parsedMoves[i + 1] : null;
    timeline.push({
      ply: i + 1,
      fen: curr.fenAfter,
      san: curr.san,
      from: curr.from,
      to: curr.to,
      turnAfter: curr.turnAfter,
      nextExpected: next ? { san: next.san, from: next.from, to: next.to } : null,
    });
  }

  return timeline;
}

